begin;

alter table public.warehouse_zones
  add column if not exists rack_levels integer not null default 4
  check (rack_levels between 1 and 20);

alter table public.warehouse_zones
  add column if not exists pallets_per_level integer not null default 2
  check (pallets_per_level between 1 and 10);

create table if not exists public.warehouse_location_movements (
  id bigint generated by default as identity primary key,
  deposit_item_id bigint not null references public.deposit_items(id) on delete cascade,
  from_zone_id uuid references public.warehouse_zones(id) on delete set null,
  from_rack_id uuid references public.warehouse_racks(id) on delete set null,
  from_bin_id uuid references public.warehouse_bins(id) on delete set null,
  to_zone_id uuid references public.warehouse_zones(id) on delete set null,
  to_rack_id uuid references public.warehouse_racks(id) on delete set null,
  to_bin_id uuid references public.warehouse_bins(id) on delete set null,
  from_location text,
  to_location text,
  moved_by text not null default 'system',
  moved_at timestamptz not null default now()
);

create index if not exists warehouse_location_movements_item_idx
  on public.warehouse_location_movements(deposit_item_id, moved_at desc);

alter table public.warehouse_location_movements enable row level security;

drop policy if exists "warehouse_location_movements_read" on public.warehouse_location_movements;
create policy "warehouse_location_movements_read"
on public.warehouse_location_movements for select
to anon, authenticated
using (true);

grant select on public.warehouse_location_movements to anon, authenticated;

create or replace function public.sync_deposit_item_storage_location()
returns trigger
language plpgsql
as $$
declare
  zone_record public.warehouse_zones%rowtype;
  rack_record public.warehouse_racks%rowtype;
  bin_record public.warehouse_bins%rowtype;
  rack_number integer;
begin
  if new.warehouse_zone_id is null then
    return new;
  end if;

  select * into zone_record
  from public.warehouse_zones
  where id = new.warehouse_zone_id;

  if not found then
    raise exception 'ไม่พบโซนที่เลือก';
  end if;

  if new.warehouse_rack_id is null or new.warehouse_bin_id is null then
    new.storage_location = concat_ws(' / ', zone_record.location_code, zone_record.floor);
    return new;
  end if;

  select * into rack_record
  from public.warehouse_racks
  where id = new.warehouse_rack_id
    and zone_id = new.warehouse_zone_id;

  if not found then
    raise exception 'Rack ที่เลือกไม่ได้อยู่ในโซนนี้';
  end if;

  select * into bin_record
  from public.warehouse_bins
  where id = new.warehouse_bin_id
    and rack_id = new.warehouse_rack_id;

  if not found then
    raise exception 'ชั้น/พาเลตที่เลือกไม่ได้อยู่ใน Rack นี้';
  end if;

  rack_number = nullif(substring(rack_record.code from '-R0*([0-9]+)$'), '')::integer;
  new.storage_location = format(
    'ช่อง %s / ชั้น %s / Rack %s / พาเลต %s',
    zone_record.location_code,
    coalesce(bin_record.shelf_level, 1),
    coalesce(rack_number, 1),
    coalesce(bin_record.col_no, 1)
  );
  return new;
end;
$$;

drop trigger if exists deposit_items_sync_storage_location on public.deposit_items;
create trigger deposit_items_sync_storage_location
before insert or update of warehouse_zone_id, warehouse_rack_id, warehouse_bin_id
on public.deposit_items
for each row execute function public.sync_deposit_item_storage_location();

create or replace function public.log_warehouse_location_movement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  jwt_claims text;
  actor_name text := 'system';
begin
  if old.warehouse_zone_id is not distinct from new.warehouse_zone_id
     and old.warehouse_rack_id is not distinct from new.warehouse_rack_id
     and old.warehouse_bin_id is not distinct from new.warehouse_bin_id then
    return new;
  end if;

  jwt_claims = current_setting('request.jwt.claims', true);
  if nullif(jwt_claims, '') is not null then
    actor_name = coalesce(jwt_claims::jsonb ->> 'email', jwt_claims::jsonb ->> 'sub', 'system');
  end if;

  insert into public.warehouse_location_movements (
    deposit_item_id,
    from_zone_id,
    from_rack_id,
    from_bin_id,
    to_zone_id,
    to_rack_id,
    to_bin_id,
    from_location,
    to_location,
    moved_by
  ) values (
    new.id,
    old.warehouse_zone_id,
    old.warehouse_rack_id,
    old.warehouse_bin_id,
    new.warehouse_zone_id,
    new.warehouse_rack_id,
    new.warehouse_bin_id,
    old.storage_location,
    new.storage_location,
    actor_name
  );
  return new;
end;
$$;

drop trigger if exists deposit_items_log_location_movement on public.deposit_items;
create trigger deposit_items_log_location_movement
after update of warehouse_zone_id, warehouse_rack_id, warehouse_bin_id
on public.deposit_items
for each row execute function public.log_warehouse_location_movement();

create or replace function public.prevent_occupied_zone_delete()
returns trigger
language plpgsql
as $$
begin
  if exists (
    select 1 from public.deposit_items
    where warehouse_zone_id = old.id
  ) then
    raise exception 'ลบโซนไม่ได้ เนื่องจากยังมีประวัติสินค้าอยู่ในโซนนี้';
  end if;
  return old;
end;
$$;

drop trigger if exists warehouse_zones_prevent_occupied_delete on public.warehouse_zones;
create trigger warehouse_zones_prevent_occupied_delete
before delete on public.warehouse_zones
for each row execute function public.prevent_occupied_zone_delete();

commit;
